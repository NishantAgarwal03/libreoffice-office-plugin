"""The Basic module installed into My Macros > Standard (pure Python, no uno).

Purpose: generate the small Basic wrapper functions that make =NUMTOWORDS(...) etc. work in cells.
         (Calc resolves cell macros from the document and from My Macros > Standard; an extension's
         own Basic library is NOT searched, hence this install step.)
Inputs/Outputs: the module name and its source text.
Must not: import uno.
"""

MODULE_NAME = "OfficePluginFunctions"
SERVICE = "org.officeplugin.FunctionJob"
HEADER = "REM Generated by Office Plugin - do not edit. Remove it with Office Plugin > Number Functions > Disable."


def source():
    q = chr(34)
    lines = [
        HEADER,
        "Function OfficePluginCall(fn As String, a As Variant, b As Variant, c As Variant, d As Variant) As Variant",
        "  Dim job As Object, args(4) As New com.sun.star.beans.NamedValue",
        "  job = CreateUnoService(%s%s%s)" % (q, SERVICE, q),
        "  args(0).Name = %sfn%s" % (q, q), "  args(0).Value = fn",
        "  args(1).Name = %sa%s" % (q, q), "  If Not IsEmpty(a) Then args(1).Value = a",
        "  args(2).Name = %sb%s" % (q, q), "  If Not IsEmpty(b) Then args(2).Value = b",
        "  args(3).Name = %sc%s" % (q, q), "  If Not IsEmpty(c) Then args(3).Value = c",
        "  args(4).Name = %sd%s" % (q, q), "  If Not IsEmpty(d) Then args(4).Value = d",
        "  OfficePluginCall = job.execute(args())",
        "End Function",
        "",
        "Function NUMTOWORDS(value As Variant, Optional numbering As Variant, Optional currency As Variant, "
        "Optional letters As Variant) As Variant",
        # 'system' is a reserved word in StarBasic: one bad name blanks EVERY function of the library
        # never assign to an Optional parameter: that is a (silent) runtime error that blanks the cell
        "  Dim s As Variant, c As Variant, l As Variant",
        "  If Not IsMissing(numbering) Then s = numbering",
        "  If Not IsMissing(currency) Then c = currency",
        "  If Not IsMissing(letters) Then l = letters",
        "  NUMTOWORDS = OfficePluginCall(%sNUMTOWORDS%s, value, s, c, l)" % (q, q),
        "End Function",
        "",
        "Function WORDSTONUM(text As Variant) As Variant",
        "  WORDSTONUM = OfficePluginCall(%sWORDSTONUM%s, text, Empty, Empty, Empty)" % (q, q),
        "End Function",
        "",
        "Function UNITSTONUM(text As Variant) As Variant",
        "  UNITSTONUM = OfficePluginCall(%sUNITSTONUM%s, text, Empty, Empty, Empty)" % (q, q),
        "End Function",
        "",
    ]
    return "\n".join(lines)
